/** Bars apart by "|", the chords in a bar apart by a space. */
const bars = (text: string) => text.split("|").map((bar) => bar.trim().split(/\s+/));
const section = (label: string, group: string, chords: string, lines?: string[]): ScoreSection => ({ label, group, bars: bars(chords), ...(lines ? { lines } : {}) });
const sing = (lyric: keyof typeof LYRICS, ...lines: number[]) => lines.map((line) => plainLine(LYRICS[lyric].lines[line]));
const song = (title: string, bpm: number, options: Partial<Omit<Score, "title" | "bpm" | "sections">>, ...sections: ScoreSection[]): Score => ({
  title,
  bpm,
  beatsPerBar: 4,
  stereo: false,
  swing: false,
  strum: "light",
  bass: "root-fifth",
  ...options,
  sections,
});

